  const table = sync.buildTable(upstream, meta, ['anthropic', 'google', 'openai-codex', 'openrouter', 'missing']);
  assert.deepEqual(Object.keys(table.providers), ['anthropic', 'google', 'openai-codex', 'openrouter']);

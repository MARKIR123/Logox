#!/usr/bin/env node
// Regenerates src/providers/model-table.generated.ts from the public `@earendil-works/pi-ai` model catalog (MIT).
// The package is only downloaded and read as data (JSON files); none of its code is imported or executed.
//
//   node scripts/sync-model-table.mjs                    # pinned version
//   node scripts/sync-model-table.mjs --latest           # newest published version
//   node scripts/sync-model-table.mjs --version 1.5.2
//   node scripts/sync-model-table.mjs --from <dir>       # use an already extracted package directory (offline)
//   node scripts/sync-model-table.mjs --check            # exit 1 when the committed file is out of date
import {execFileSync, execSync} from 'node:child_process';
import {mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {dirname, join, resolve} from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';

export const PACKAGE = '@earendil-works/pi-ai';
export const PINNED_VERSION = '1.5.2';
/** Catalog providers LOGOX can meaningfully resolve against: first-party vendors, ChatGPT/Copilot subscriptions and the OpenRouter gateway. */
export const KEEP_PROVIDERS = ['anthropic', 'deepseek', 'github-copilot', 'google', 'google-vertex', 'minimax', 'mistral', 'moonshotai',
  'openai', 'openai-codex', 'openrouter', 'xai', 'zai'];
/** Providers billed through a subscription, so token prices are API-equivalent estimates rather than charges. */
export const SUBSCRIPTION_PROVIDERS = ['github-copilot', 'openai-codex'];
const FALLBACK_COPYRIGHT = 'Copyright (c) 2025 Mario Zechner';
const LICENSE_URL = 'https://raw.githubusercontent.com/earendil-works/pi/main/LICENSE';
const LEVEL_ORDER = ['off', 'minimal', 'low', 'medium', 'high', 'xhigh', 'max'];

/** Mirrors upstream getSupportedThinkingLevels: null removes a level; xhigh/max need an explicit mapping. */
export function thinkingLevels(model) {
  if (!model.reasoning) return ['off'];
  const map = model.thinkingLevelMap ?? {};
  return LEVEL_ORDER.filter(level => {
    const mapped = map[level];
    if (mapped === null) return false;
    return level === 'xhigh' || level === 'max' ? mapped !== undefined : true;
  });
}
const rate = value => typeof value === 'number' && Number.isFinite(value) ? value : 0;
/** One compact tuple per model: [id, name, window, maxOutput, input modalities, reasoning levels ('' = not a reasoning model), [input, output, cacheRead, cacheWrite], tiers?]. */
export function trimModel(model) {
  const cost = model.cost ?? {};
  const row = [model.id, model.name ?? model.id, model.contextWindow, model.maxTokens, (model.input ?? ['text']).join(','),
    model.reasoning ? thinkingLevels(model).join(',') : '', [rate(cost.input), rate(cost.output), rate(cost.cacheRead), rate(cost.cacheWrite)]];
  const tiers = (cost.tiers ?? []).filter(tier => typeof tier.inputTokensAbove === 'number')
    .map(tier => [tier.inputTokensAbove, rate(tier.input), rate(tier.output), rate(tier.cacheRead), rate(tier.cacheWrite)]);
  if (tiers.length > 0) row.push(tiers);
  return row;
}
/** Flattens upstream `{api: {"chat:<id>": model}}` groups the way the package does (later groups win) and keeps chat models only. */
export function chatModels(groups) {
  const byId = new Map();
  for (const group of Object.values(groups)) {
    for (const model of Object.values(group)) {
      if (model && model.type === 'chat' && typeof model.id === 'string' && Number.isFinite(model.contextWindow) && Number.isFinite(model.maxTokens)) byId.set(model.id, model);
    }
  }
  return byId;
}
/** Pure transform: `files` maps provider name to its parsed upstream JSON. Output order and formatting are deterministic. */
export function buildTable(files, meta, keep = KEEP_PROVIDERS) {
  const providers = {};
  for (const name of [...keep].sort()) {
    const groups = files[name];
    if (!groups) continue;
    const models = [...chatModels(groups).values()].sort((a, b) => a.id < b.id ? -1 : a.id > b.id ? 1 : 0).map(trimModel);
    if (models.length > 0) providers[name] = {subscription: SUBSCRIPTION_PROVIDERS.includes(name), models};
  }
  return {source: meta.source, version: meta.version, upstreamDate: meta.upstreamDate, providers};
}
export function renderTable(table, copyright = FALLBACK_COPYRIGHT) {
  const providerLines = Object.entries(table.providers).map(([name, entry]) =>
    '    ' + JSON.stringify(name) + ': {subscription: ' + entry.subscription + ', models: [\n' + entry.models.map(row => '      ' + JSON.stringify(row)).join(',\n') + ',\n    ]},');
  return [
    '// GENERATED by scripts/sync-model-table.mjs. Do not edit; run `npm run sync:models` to refresh.',
    '// Source: ' + table.source + '@' + table.version + ' (upstream catalog generated ' + table.upstreamDate + ').',
    '// The upstream package is MIT licensed. ' + copyright + '. Permission is hereby granted, free of charge, to any person obtaining',
    '// a copy of this data to deal in it without restriction, subject to the MIT notice (https://opensource.org/license/mit).',
    '// Prices are USD per 1M tokens; windows and limits are tokens. Row layout is documented by ModelRow in model-table.ts.',
    "import type {ModelTableData} from './model-table.js';",
    '',
    'export const modelTableData: ModelTableData = {',
    '  source: ' + JSON.stringify(table.source) + ',',
    '  version: ' + JSON.stringify(table.version) + ',',
    '  upstreamDate: ' + JSON.stringify(table.upstreamDate) + ',',
    '  providers: {',
    ...providerLines,
    '  },',
    '};',
    '',
  ].join('\n');
}
/** Reads the extracted package's per-provider JSON catalog files as data. */
export function readPackage(directory) {
  const dataDir = join(directory, 'dist', 'providers', 'data');
  const files = {};
  for (const entry of readdirSync(dataDir).sort()) {
    if (!entry.endsWith('.json') || entry.startsWith('.')) continue;
    files[entry.slice(0, -5)] = JSON.parse(readFileSync(join(dataDir, entry), 'utf8'));
  }
  let upstreamDate = 'unknown';
  try {upstreamDate = String(JSON.parse(readFileSync(join(dataDir, '.manifest.json'), 'utf8')).generatedAt ?? 'unknown').slice(0, 10);} catch {}
  const version = JSON.parse(readFileSync(join(directory, 'package.json'), 'utf8')).version;
  return {files, meta: {source: PACKAGE, version, upstreamDate}};
}
function pack(version, work) {
  if (!/^(latest|\d+\.\d+\.\d+(-[\w.]+)?)$/.test(version)) throw new Error('Invalid version: ' + version);
  const out = execSync('npm pack ' + PACKAGE + '@' + version + ' --silent', {cwd: work, encoding: 'utf8'}).trim().split(/\r?\n/).at(-1);
  const extract = join(work, 'x');
  mkdirSync(extract);
  execFileSync('tar', ['-xzf', out, '-C', 'x'], {cwd: work}); // relative paths: GNU tar reads "C:" as a remote host
  return join(extract, 'package');
}
async function upstreamCopyright() {
  try {
    const response = await fetch(LICENSE_URL, {signal: AbortSignal.timeout(15000)});
    const match = response.ok ? /^Copyright \(c\) .+$/m.exec(await response.text()) : null;
    if (match) return match[0].trim();
  } catch {}
  return FALLBACK_COPYRIGHT;
}
async function main() {
  const args = process.argv.slice(2);
  const option = name => { const at = args.indexOf(name); return at >= 0 ? args[at + 1] : undefined; };
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  const target = resolve(option('--out') ?? join(root, 'src', 'providers', 'model-table.generated.ts'));
  let directory = option('--from'), work;
  if (!directory) {
    work = mkdtempSync(join(tmpdir(), 'logox-model-sync-'));
    directory = pack(args.includes('--latest') ? 'latest' : option('--version') ?? PINNED_VERSION, work);
  }
  try {
    const {files, meta} = readPackage(resolve(directory));
    const text = renderTable(buildTable(files, meta), await upstreamCopyright());
    if (args.includes('--check')) {
      let current = '';
      try {current = readFileSync(target, 'utf8');} catch {}
      if (current !== text) {console.error('model-table.generated.ts is out of date for ' + meta.version); process.exitCode = 1;}
      return;
    }
    writeFileSync(target, text);
    const models = Object.values(buildTable(files, meta).providers).reduce((sum, entry) => sum + entry.models.length, 0);
    console.log('Wrote ' + target + ' (' + meta.source + '@' + meta.version + ', ' + models + ' models, ' + Buffer.byteLength(text) + ' bytes)');
  } finally {
    if (work) rmSync(work, {recursive: true, force: true});
  }
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) await main();
